import { test, expect } from '@playwright/test'
import { readFileSync } from 'node:fs'
const runtime = process.env.TRIAL_RUNTIME_FILE ? JSON.parse(readFileSync(process.env.TRIAL_RUNTIME_FILE, 'utf8')) : null
test('both landing forms share searchable Support, type filters and persistent status controls', async ({page,browser}) => {
 test.setTimeout(90000)
 test.skip(!runtime, 'Requires owned disposable backend and PostgreSQL')
 const marker=crypto.randomUUID()
 await page.addInitScript(()=>localStorage.setItem('syrian-menu-language','en'))
 await page.goto(runtime.site)
 for(const [name,value] of Object.entries({name:'Visitor',email:'unified@example.test',subject:`Contact ${marker}`,message:'Please send information'})) await page.locator(`#contact-${name}`).fill(value)
 await page.locator('.contact-submit').click()
 await expect(page.locator('.contact-success')).toBeVisible()
 for(const [name,value] of Object.entries({restaurantName:`Trial ${marker}`,applicantName:'Applicant',email:'unified@example.test',phone:'+963 944 123 456',message:'Please review our request'})) await page.locator(`#trial-${name}`).fill(value)
 await page.locator('#free-trial .trial-submit').click()
 await expect(page.locator('#free-trial .trial-success')).toBeVisible()
 const settings=JSON.parse(readFileSync(runtime.settingsFile,'utf8'))
 const context=await browser.newContext()
 expect((await context.request.post(`${runtime.api}/auth/login`,{headers:{Origin:runtime.admin},data:{email:settings.SEED_ADMIN_EMAIL,password:settings.SEED_ADMIN_PASSWORD}})).status()).toBe(200)
 const admin=await context.newPage()
 await admin.goto(`${runtime.admin}/support`)
 await admin.getByRole('searchbox').fill(marker)
 await admin.getByRole('button',{name:'Search',exact:true}).click()
 await expect(admin.locator('.support-inbox-row')).toHaveCount(2)
 for(const [kind,title] of [['CONTACT','Contact'],['TRIAL','Trial']]) {
  await admin.getByLabel('Type',{exact:true}).selectOption(kind)
  await expect(admin.locator('.support-inbox-row')).toHaveCount(1)
  await admin.locator('.support-inbox-row').click()
  await expect(admin.locator('.support-contact-details')).toContainText('unified@example.test')
  await admin.locator('#contact-status').selectOption('RESOLVED')
  await admin.getByRole('button',{name:'Update status',exact:true}).click()
  await expect(admin.getByRole('status').filter({hasText:'Status saved.'})).toBeVisible()
  await admin.reload()
  await expect(admin.locator('#contact-status')).toHaveValue('RESOLVED')
  await admin.getByRole('link',{name:'Back to support inbox'}).click()
  await admin.getByLabel('Status',{exact:true}).selectOption('RESOLVED')
  await expect(admin.locator('.support-inbox-row')).toContainText(`${title} ${marker}`)
  await admin.getByLabel('Status',{exact:true}).selectOption('')
 }
 await admin.getByLabel('Type',{exact:true}).selectOption('')
 await expect(admin.locator('.support-inbox-row')).toHaveCount(2)
 await admin.setViewportSize({width:390,height:844})
 expect(await admin.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await admin.screenshot({path:'artifacts/contact/unified-support-mobile.png',fullPage:true})
 await context.close()
})

